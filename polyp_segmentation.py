class BCEIoULoss(nn.Module):
    def __init__(self):
        super().__init__()
    def forward(self, logits, targets, weight=None, eps=1e-7):
        bce = F.binary_cross_entropy_with_logits(logits, targets, weight=weight)
        probs = torch.sigmoid(logits)
        probs = probs.view(-1)
        targets = targets.view(-1)
        if weight is not None:
            weight = weight.view(-1)
            intersection = (weight * probs * targets).sum()
            union = (weight * (probs + targets - probs * targets)).sum()
        else:
            intersection = (probs * targets).sum()
            union = (probs + targets - probs * targets).sum()
        iou = (intersection + eps) / (union + eps)
        iou_loss = 1 - iou
        return bce + iou_loss

criterion = BCEIoULoss()

