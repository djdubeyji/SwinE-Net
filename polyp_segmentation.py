# --- MixUp and CutMix for segmentation ---
def mixup_segmentation(images, masks, alpha=0.4):
    '''images: [B, C, H, W], masks: [B, 1, H, W]'''
    lam = np.random.beta(alpha, alpha)
    batch_size = images.size(0)
    index = torch.randperm(batch_size).to(images.device)
    mixed_images = lam * images + (1 - lam) * images[index, :]
    mixed_masks = lam * masks + (1 - lam) * masks[index, :]
    return mixed_images, mixed_masks

def rand_bbox(size, lam):
    W = size[2]
    H = size[3]
    cut_rat = np.sqrt(1. - lam)
    cut_w = np.int32(W * cut_rat)
    cut_h = np.int32(H * cut_rat)
    # uniform
    cx = np.random.randint(W)
    cy = np.random.randint(H)
    bbx1 = np.clip(cx - cut_w // 2, 0, W)
    bby1 = np.clip(cy - cut_h // 2, 0, H)
    bbx2 = np.clip(cx + cut_w // 2, 0, W)
    bby2 = np.clip(cy + cut_h // 2, 0, H)
    return bbx1, bby1, bbx2, bby2

def cutmix_segmentation(images, masks, alpha=0.4):
    '''images: [B, C, H, W], masks: [B, 1, H, W]'''
    lam = np.random.beta(alpha, alpha)
    batch_size = images.size(0)
    index = torch.randperm(batch_size).to(images.device)
    bbx1, bby1, bbx2, bby2 = rand_bbox(images.size(), lam)
    images_cutmix = images.clone()
    masks_cutmix = masks.clone()
    images_cutmix[:, :, bbx1:bbx2, bby1:bby2] = images[index, :, bbx1:bbx2, bby1:bby2]
    masks_cutmix[:, :, bbx1:bbx2, bby1:bby2] = masks[index, :, bbx1:bbx2, bby1:bby2]
    return images_cutmix, masks_cutmix

