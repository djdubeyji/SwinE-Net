num_kvasir = len(dataset_kvasir)
num_clinicdb = len(dataset_clinicdb)
val_indices_clinicdb = [idx - num_kvasir for idx in val_indices if idx >= num_kvasir]
clinicdb_val_dataset = Subset(dataset_clinicdb, val_indices_clinicdb)
clinicdb_val_loader = DataLoader(clinicdb_val_dataset, batch_size=8, shuffle=False)

# --- Evaluate on ClinicDB val set ---
model.eval()
dice_total = 0.0
iou_total = 0.0
acc_total = 0.0
n_batches = 0

with torch.no_grad():
    for images, masks in clinicdb_val_loader:
        images = images.cuda()
        masks = masks.cuda()
        logits = model(images)
        probs = torch.sigmoid(logits)
        preds = (probs > 0.5).float()
        if preds.ndim == 4:
            preds = preds[:, 0]
            masks = masks[:, 0]
        dice = dice_coefficient(preds.cpu(), masks.cpu())
        iou = iou_score(preds.cpu(), masks.cpu())
        acc = pixel_accuracy(preds.cpu(), masks.cpu())
        dice_total += dice
        iou_total += iou
        acc_total += acc
        n_batches += 1

print(f"ClinicDB Validation Metrics:")
print(f"Mean Dice: {dice_total / n_batches:.4f}")
print(f"Mean IoU: {iou_total / n_batches:.4f}")
print(f"Mean Accuracy: {acc_total / n_batches:.4f}")